// Writes the generated native play scripts from the rules and the content:
//  - tests/native/journey-1.play: Journey stage 1 on a desktop (1280 × 800),
//    from the title through the modes and the stage grid, every lit cell
//    clicked on the cells' named targets (a drag paints a run), to the
//    results and the next stage's board;
//  - tests/native/learn-phone.play: the five lessons on a phone (390 × 844,
//    DPR 3), each step's moves touched on the named cells (Mark mode and Hint
//    from the tray), each lesson to its results and back to Learn.
// The lesson moves follow main.ts's gating (each step's count clamped to
// what is left on the live board, steps already satisfied skipped), played
// on the rules so line propagation is accounted for.
//   node tools/gen-plays.mjs
import { writeFileSync } from 'node:fs';
import { createState, applyCommand, CELL } from '../js/rules.js';
import { LESSONS, JOURNEY_STAGES } from '../js/content.js';
import { journeyPuzzle } from '../js/puzzles.js';

const out = (name, lines) => { writeFileSync(new URL(`../tests/native/${name}`, import.meta.url), lines.join('\n') + '\n'); console.log(`tests/native/${name}: ${lines.length} lines`); };
const cellName = (r, c, v) => `Row ${r + 1}, column ${c + 1}, ${v === CELL.FILLED ? 'lit' : v === CELL.MARKED ? 'crossed' : 'unknown'}`;

// ---- Journey 1, clicked (the first row painted with a drag across its run)
{
  const stage = JOURNEY_STAGES[0];
  const p = journeyPuzzle(stage);
  const s = createState({ ...p, parMs: stage.parMs, constraints: stage.constraints });
  const L = [
    '# Generated by tools/gen-plays.mjs: Journey stage 1 on a desktop (1280 x 800), from the title through the',
    '# modes and the stage grid, every lit cell clicked on the cells\' named targets, to the results and the',
    '# next stage\'s board.',
    '# viewport 1280x800@1',
    'until 600 Read the clues', 'frames 10', 'save title', 'click =Play', 'until 120 Choose a mode', 'frames 10', 'save modes',
    'click =Journey', 'until 120 Forty authored light-boards', 'frames 10', 'save journey',
    'click =Stage 1, 5 by 5', 'until 300 Row 1, column 1, unknown', 'frames 200', 'save journey-board',
  ];
  for (let i = 0; i < s.solution.length; i++) {
    if (!s.solution[i] || s.grid[i] === CELL.FILLED) continue;
    const r = Math.floor(i / s.cols), c = i % s.cols;
    L.push(`click =${cellName(r, c, s.grid[i])}`, 'frames 4');
    applyCommand(s, { type: 'fill', r, c });
  }
  if (s.status !== 'complete') throw new Error('journey 1 not solved');
  L.push('until 400 Picture revealed', 'frames 20', 'expect Stage stars: ★★★', 'save journey-results', 'click =Next stage 2',
    'until 300 Journey 2', 'frames 150', 'save journey-2');
  out('journey-1.play', L);
}

// ---- the five lessons on a phone
{
  const L = [
    '# Generated by tools/gen-plays.mjs: the five lessons on a phone (390 x 844, DPR 3), each step\'s moves touched',
    '# on the named cells (Mark mode and Hint from the tray), each lesson to its results and back to Learn.',
    '# viewport 390x844@3',
    'until 600 Read the clues', 'frames 10', 'touch =Play', 'until 120 Choose a mode', 'frames 10',
    'touch =Learn', 'until 120 One rule at a time', 'frames 10', 'save learn-list',
  ];
  LESSONS.forEach((lesson, li) => {
    const s = createState({ id: lesson.id, seed: 1, rows: lesson.board.rows, cols: lesson.board.cols, solution: lesson.board.solution, parMs: 600000,
      constraints: { allowHints: lesson.id === 'lesson-5', allowUndo: true } });
    let mode = 'fill';
    L.push(`touch =${li + 1}. ${lesson.name}`, 'until 300 step 1/', 'frames 40');
    if (li === 1) L.push('save lesson-2');
    const remaining = (req, mark) => {
      const cells = [];
      for (let i = 0; i < s.solution.length; i++) {
        const r = Math.floor(i / s.cols), c = i % s.cols;
        if (req.r !== undefined && req.r !== r) continue;
        if (req.c !== undefined && req.c !== c) continue;
        if (mark ? s.solution[i] === 0 && s.grid[i] === CELL.UNKNOWN : s.solution[i] === 1 && s.grid[i] !== CELL.FILLED) cells.push([r, c]);
      }
      return cells;
    };
    for (const step of lesson.steps) {
      const req = step.require;
      if (s.status !== 'active') break;
      if (req.type === 'hint') {
        L.push('touch =Hint', 'frames 20');
        applyCommand(s, { type: 'hint' });
        continue;
      }
      const mark = req.type === 'mark';
      const cells = remaining(req, mark);
      if (!cells.length) continue;
      const n = Math.min(step.requireCount ?? cells.length, cells.length);
      const want = mark ? 'mark' : 'fill';
      if (mode !== want) { L.push(`touch =${mark ? 'Mark' : 'Fill'}`, 'frames 6'); mode = want; }
      for (const [r, c] of cells.slice(0, n)) {
        L.push(`touch =${cellName(r, c, s.grid[r * s.cols + c])}`, 'frames 6');
        applyCommand(s, { type: want, r, c });
      }
    }
    if (s.status !== 'complete') {
      // Finish the picture (the last steps may leave lit cells after the lesson ends).
      if (mode !== 'fill') { L.push('touch =Fill', 'frames 6'); mode = 'fill'; }
      for (let i = 0; i < s.solution.length; i++) {
        if (s.solution[i] && s.grid[i] !== CELL.FILLED) { const r = Math.floor(i / s.cols), c = i % s.cols; L.push(`touch =${cellName(r, c, s.grid[i])}`, 'frames 6'); applyCommand(s, { type: 'fill', r, c }); }
      }
    }
    if (mode !== 'fill') { L.push('touch =Fill', 'frames 6'); }
    L.push('until 400 Picture revealed', 'frames 10', `expect Lessons complete: ${li + 1}/5.`);
    if (li === 0) L.push('save lesson-results');
    L.push('touch =Continue', 'until 120 One rule at a time', 'frames 10');
  });
  L.push('save learn-done');
  out('learn-phone.play', L);
}
