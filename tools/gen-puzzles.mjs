// Precomputes the 40 Journey puzzles into js/puzzles.js: content.js's seeded,
// unique-solution generator (rules.js solve) takes up to ~0.4 s a stage in
// the engine's interpreter (~20× slower than V8), so the fixed stages ship as
// a table; tests/content.test.mjs checks it still equals buildPuzzle's output.
// Daily, Practice and Challenge boards are generated on a script worker
// (native/gen-worker.js). Run after changing the generator or the journey.
import { writeFileSync } from 'node:fs';
import { JOURNEY_STAGES, generatePuzzle, CONTENT_VERSION } from '../js/content.js';

const rows = JOURNEY_STAGES.map((s) => {
  const g = generatePuzzle(s);
  return `  ${JSON.stringify(s.id)}: [${g.seed}, ${JSON.stringify(g.solution.join(''))}],`;
});
const src = `// Generated by tools/gen-puzzles.mjs (content v${CONTENT_VERSION}): the Journey stages' puzzles as
// content.js generatePuzzle makes them — id: [attempt seed, solution bits by row] — so the engine
// client starts a stage without running the solver. tests/content.test.mjs checks the table.
'use strict';

import { namePuzzle, THEMES } from './content.js';

export const JOURNEY_TABLE = {
${rows.join('\n')}
};

/** content.js buildPuzzle(stage) for a Journey stage, from the table (null when it is not there). */
export function journeyPuzzle(spec) {
  const row = JOURNEY_TABLE[spec.id];
  if (!row || row[1].length !== spec.rows * spec.cols) return null;
  const [seed, bits] = row;
  return {
    id: spec.id, seed, rows: spec.rows, cols: spec.cols,
    solution: Array.from(bits, (b) => (b === '1' ? 1 : 0)),
    constraints: spec.constraints || {}, parMs: spec.parMs, name: namePuzzle(seed),
    theme: spec.theme || THEMES[0].id, ranked: !!spec.ranked, meta: spec,
  };
}
`;
writeFileSync(new URL('../js/puzzles.js', import.meta.url), src);
console.log(`js/puzzles.js: ${rows.length} stages`);
